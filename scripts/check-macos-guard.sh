#!/usr/bin/env bash
# Type-check the macOS guard against apple-shaped `libc` shims.
#
# CI's `test` job matrix includes `macos-latest`, so the guard in
# `crates/qcode-tools/src/procguard.rs` (`#[cfg(target_os = "macos")]`) does get a
# real compiler there. This script is not a replacement for that job. It exists
# because a developer on Linux cannot compile that file at all, and a `cfg`'d-out
# module is one refactor away from not compiling on the platform it is for:
#
#   * the *real* module bodies are extracted from the source (never copied by
#     hand, so they cannot drift from what ships) — and the extraction
#     self-checks, so a change to the module's shape fails loudly instead of
#     silently checking a slice of unrelated code;
#   * `libc` is replaced by a shim whose signatures and constants are copied from
#     libc 0.2.191's `unix/bsd/apple` and `unix/bsd` modules;
#   * `rustc --emit=metadata` type-checks the pair, in about a second.
#
# Two modules are checked: `guard` (the platform-independent half) and `watch`
# (the macOS half — `kqueue` + `EVFILT_PROC`). Linux's `watch` needs
# `pidfd_open` + `poll` and is checked by actually compiling it, since the
# development platform is Linux.
#
# What this catches: wrong argument types, wrong `kevent` field types, drift in
# the libc signature, `unsafe` blocks that no longer type-check.
# What it does NOT catch: a wrong constant *value* that has the right type, or
# any runtime behaviour. Not a substitute for the macOS regression checklist in
# ADR-0074, and not a substitute for `test (macos-latest)`.
#
# Exit status is the compiler's, so this gates CI.
set -euo pipefail

repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
source_file="$repo/crates/qcode-tools/src/procguard.rs"
work="$repo/target/macos-guard-check"

[[ -f $source_file ]] || {
    echo "missing $source_file" >&2
    exit 1
}

rm -rf "$work"
mkdir -p "$work/src"

# Print the body (between the braces) of the module whose opening line is
# `mod <name> {`, optionally requiring `#[cfg(... "<os>")]` on the line just
# before it. There are two `mod watch` blocks in the file, one per platform, so
# the cfg check is what picks the right one.
extract_module() {
    local name=$1 os=$2 out=$3
    local start end
    start=$(awk -v want="mod $name {" -v os="$os" '
        { prev = cur; cur = $0 }
        cur == want {
            if (os == "" || prev ~ ("target_os = \"" os "\"")) { print NR; exit }
        }
    ' "$source_file")
    if [[ -z ${start:-} ]]; then
        echo "could not find 'mod $name'${os:+ gated on $os} in $source_file" >&2
        return 1
    fi
    end=$(awk -v s="$start" 'NR > s && /^}$/ { print NR; exit }' "$source_file")
    if [[ -z ${end:-} ]]; then
        echo "could not find the end of 'mod $name' in $source_file" >&2
        return 1
    fi
    sed -n "$((start + 1)),$((end - 1))p" "$source_file" >"$out"
}

extract_module guard "" "$work/src/guard_body.rs"
extract_module watch macos "$work/src/watch_body.rs"

# The one path that reaches the crate root is rewritten; nothing else in the code
# under test is touched.
sed -i 's|^    use super::{GUARD_ARG, Table};$|    use crate::{GUARD_ARG, Table};|' \
    "$work/src/guard_body.rs"
grep -q 'use crate::{GUARD_ARG, Table};' "$work/src/guard_body.rs" || {
    echo "the 'use super::{GUARD_ARG, Table};' line moved; update this script" >&2
    exit 1
}

# The bodies are a module's *contents*, so each needs a `libc` in scope pointing
# at the shim. Prepended here rather than folded into the extraction so the
# extracted text stays identical to the real file.
sed -i '1i\    use crate::libc;' "$work/src/guard_body.rs"
sed -i '1i\    use crate::libc;' "$work/src/watch_body.rs"

cat > "$work/src/lib.rs" <<'RS'
//! Generated by scripts/check-macos-guard.sh — do not edit.
#![allow(dead_code)]
// The shim mirrors C names on purpose: it has to look like `libc`.
#![allow(non_camel_case_types)]

mod libc {
    // Signatures and types copied from libc 0.2.191 `unix/bsd/apple` + `unix/bsd`.
    pub type c_int = i32;
    pub type c_void = core::ffi::c_void;
    pub type uintptr_t = usize;
    pub type intptr_t = isize;
    pub type pid_t = i32;

    pub const EVFILT_READ: i16 = -1;
    pub const EVFILT_PROC: i16 = -5;
    pub const EV_ADD: u16 = 0x1;
    pub const EV_ONESHOT: u16 = 0x10;
    pub const EV_EOF: u16 = 0x8000;
    pub const NOTE_EXIT: u32 = 0x8000_0000;
    pub const SIGKILL: c_int = 9;
    pub const F_GETFL: c_int = 3;
    pub const F_SETFL: c_int = 4;
    pub const O_NONBLOCK: c_int = 0x4;

    #[repr(C)]
    pub struct timespec {
        pub tv_sec: i64,
        pub tv_nsec: i64,
    }

    #[repr(C)]
    pub struct kevent {
        pub ident: uintptr_t,
        pub filter: i16,
        pub flags: u16,
        pub fflags: u32,
        pub data: intptr_t,
        pub udata: *mut c_void,
    }

    extern "C" {
        pub fn kqueue() -> c_int;
        pub fn kevent(
            kq: c_int,
            changelist: *const kevent,
            nchanges: c_int,
            eventlist: *mut kevent,
            nevents: c_int,
            timeout: *const timespec,
        ) -> c_int;
        pub fn setsid() -> pid_t;
        pub fn killpg(pgrp: pid_t, sig: c_int) -> c_int;
        pub fn read(fd: c_int, buf: *mut c_void, count: usize) -> isize;
        pub fn fcntl(fd: c_int, cmd: c_int, ...) -> c_int;
    }
}

pub const GUARD_ARG: &str = "__qcode-procguard";

/// Stand-in with the same shape as the real protocol table: this check is about
/// the FFI calls, and the table carries its own tests.
#[derive(Default)]
pub(crate) struct Table;

impl Table {
    pub(crate) fn feed(&mut self, _chunk: &[u8]) {}
    pub(crate) fn live(&self) -> Vec<u32> {
        Vec::new()
    }
}

mod watch {
    include!("watch_body.rs");
}

mod guard {
    include!("guard_body.rs");
}
RS

cd "$work"
rustc --edition 2021 --crate-type lib --emit=metadata -o guard_check.rmeta src/lib.rs
echo "macOS guard type-checks against apple libc signatures"
